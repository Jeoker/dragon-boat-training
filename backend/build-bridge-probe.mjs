import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const backendDir = dirname(fileURLToPath(import.meta.url));
const sourceDir = join(backendDir, "src");
const outputDir = join(backendDir, ".build");
const probeDir = join(outputDir, "bridge-probe");
const outputFile = join(probeDir, "Code.gs");
const sources = [
  [sourceDir, "Config.gs"],
  [sourceDir, "Security.gs"],
  [sourceDir, "BridgeSecurity.gs"],
  [join(backendDir, "bridge-probe"), "Setup.gs"],
  [sourceDir, "Code.gs"]
];

const parts = [];
for (const [directory, source] of sources) {
  parts.push(`// ---- ${source} ----\n${await readFile(join(directory, source), "utf8").then((text) => text.trim())}`);
}

await mkdir(probeDir, { recursive: true });
await writeFile(
  outputFile,
  `// Generated by backend/build-bridge-probe.mjs. Do not edit this file directly.\n\n${parts.join("\n\n")}\n`,
  "utf8"
);
await writeFile(
  join(probeDir, "appsscript.json"),
  `${JSON.stringify({
    timeZone: "America/New_York",
    dependencies: {},
    exceptionLogging: "STACKDRIVER",
    runtimeVersion: "V8",
    executionApi: {
      access: "MYSELF"
    },
    webapp: {
      executeAs: "USER_DEPLOYING",
      access: "ANYONE_ANONYMOUS"
    }
  }, null, 2)}\n`,
  "utf8"
);
console.log(outputFile.replaceAll("\\", "/"));
